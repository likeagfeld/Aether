"""Generate menu/pop/plogo.c: the About popup's Aether lockup (mark, AETHER, saturn) on its navy tile, as a VDP1
16-colour lookup-table sprite (4 bpp) that POPUP.BIN carries.

Source: manager/VibeMenuCardManager.UI/Assets/about_lockup.png, the Card Manager's About logo (the same picture on
both About pages). It is trimmed, fitted inside the tile with a margin (LANCZOS, premultiplied by Pillow), laid over
the tile's navy (the Card Manager's BrandPlate, #0B2A6B) and reduced to 15 levels of brightness (indexed); index 0 is
transparent and rounds the tile's corners. W is a multiple of 8 (HWF-06).

The omsat-build image has no Pillow, so the output is committed; tools/tests/test_aboutlogo.py checks it is in step
with the PNG. `python -m omsat.gen_aboutlogo` writes it."""
from __future__ import annotations

from pathlib import Path

from PIL import Image, ImageFilter

ROOT = Path(__file__).resolve().parents[2]
SRC = ROOT / "manager" / "VibeMenuCardManager.UI" / "Assets" / "about_lockup.png"
OUT = ROOT / "menu" / "pop" / "plogo.c"
W, H = 88, 68               # the tile; W a multiple of 8
MARGIN_X, MARGIN_Y = 5, 3   # the lockup's room inside it
NAVY = (0x0B, 0x2A, 0x6B)
RADIUS = 4                  # the tile's rounded corners (transparent)
GAMMA = 1.6


def _rgb555(c: tuple[int, int, int]) -> int:
    r, g, b = (round(v * 31 / 255) for v in c)
    return 0x8000 | b << 10 | g << 5 | r


def _corner(x: int, y: int) -> bool:
    """outside the rounded rectangle"""
    cx = RADIUS - 1 - x if x < RADIUS else x - (W - RADIUS) if x >= W - RADIUS else -1
    cy = RADIUS - 1 - y if y < RADIUS else y - (H - RADIUS) if y >= H - RADIUS else -1
    return cx >= 0 and cy >= 0 and (cx + 0.5) ** 2 + (cy + 0.5) ** 2 > RADIUS ** 2


def render(src: Path = SRC) -> Image.Image:
    """The tile, RGB, W x H."""
    with Image.open(src) as im:
        im = im.convert("RGBA")
        im = im.crop(im.getbbox())
    bw, bh = W - 2 * MARGIN_X, H - 2 * MARGIN_Y
    k = min(bw / im.width, bh / im.height)
    sw, sh = max(1, round(im.width * k)), max(1, round(im.height * k))
    im = im.resize((sw, sh), Image.LANCZOS)
    tile = Image.new("RGBA", (W, H), NAVY + (255,))
    tile.alpha_composite(im, ((W - sw) // 2, (H - sh) // 2))
    return tile.convert("RGB")


def indexed(src: Path = SRC) -> tuple[list[int], list[int]]:
    """(the 16 LUT words: 0 transparent, then 15 RGB555 colours; W x H indices 0..15). The picture is one tint over
    navy, so the levels are bins of brightness above the navy (spaced by GAMMA: more of them in the faint glow), each
    the mean colour of its pixels; a light unsharp mask first keeps the thin strokes bright at this size."""
    raw = render(src).filter(ImageFilter.UnsharpMask(1, 60, 0)).tobytes()
    px = [tuple(raw[i:i + 3]) for i in range(0, len(raw), 3)]
    nl = sum(NAVY)
    top = max(max(sum(p) for p in px) - nl, 1)
    level = [min(14, round((max(0, sum(p) - nl) / top) ** (1 / GAMMA) * 14)) for p in px]
    acc = [[0, 0, 0, 0] for _ in range(15)]
    for p, k in zip(px, level):
        a = acc[k]
        a[0] += p[0]; a[1] += p[1]; a[2] += p[2]; a[3] += 1
    cols = [tuple(v // a[3] for v in a[:3]) if a[3] else
            tuple(round(n + (255 - n) * (k / 14) ** GAMMA) for n in NAVY) for k, a in enumerate(acc)]
    lut = [0] + [_rgb555(c) for c in cols]
    idx = [0 if _corner(i % W, i // W) else level[i] + 1 for i in range(W * H)]
    return lut, idx


def make(src: Path = SRC) -> str:
    lut, px = indexed(src)
    nib = bytes(px[i] << 4 | px[i + 1] for i in range(0, W * H, 2))
    rows = [", ".join(f"0x{b:02X}" for b in nib[i:i + 22]) for i in range(0, len(nib), 22)]
    return ("/* menu/pop/plogo.c -- GENERATED by tools/omsat/gen_aboutlogo.py from the Card Manager's About logo\n"
            " * (manager/VibeMenuCardManager.UI/Assets/about_lockup.png): the About popup's Aether lockup on its navy tile,\n"
            f" * {W} x {H}, 4 bpp, a 16-colour lookup table (0 transparent). Do not edit. BSD-3-Clause. */\n"
            "#include \"pabout.h\"\n\n"
            f"const uint16_t om_pa_logo_lut[16] = {{ {', '.join(f'0x{v:04X}' for v in lut)} }};\n"
            f"const uint8_t om_pa_logo[{W * H // 2}] __attribute__((aligned(4))) = {{\n    "
            + ",\n    ".join(rows) + "\n};\n")


if __name__ == "__main__":
    OUT.write_text(make(), newline="\n")
    print(f"wrote {OUT}")
