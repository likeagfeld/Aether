#!/usr/bin/env python3
"""Turn contract fixtures into C tables for the host tests. Stdlib only (omsat-build has no Pillow)."""
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
FIX = ROOT / "contract" / "fixtures"
sys.path.insert(0, str(ROOT / "tools"))
from omsat.lnchhdr import make_header  # noqa: E402  (stdlib-only module)
from omsat import bupfile  # noqa: E402  (stdlib-only module)


def c(s):
    if s is None:
        return "NULL"
    out = []
    for b in s.encode("utf-8"):
        if b in (0x22, 0x5C):
            out.append("\\" + chr(b))
        elif 0x20 <= b < 0x7F:
            out.append(chr(b))
        else:
            out.append("\\%03o" % b)
    return '"' + "".join(out) + '"'


def cb(b):
    return '"' + "".join("\\%03o" % x for x in b) + '"'


def bup_cases(o, rows=None):
    """the 326 real .BUP headers of Kai's release (kai_bup_headers.json) with the
    Python codec's verdicts, so the C decoder and om_bup_prefer are checked against the same corpus. M6 Task 23 (Task 22
    re-review Minor): KB_DUP's rows are KB_DUP_W wide -- the largest duplicate group, at least 4 -- so no member is cut,
    and test_bupfile.c bounds its loop by it. rows: a test's own header list instead of the fixture."""
    if rows is None:
        rows = json.loads((FIX / "kai_bup_headers.json").read_text(encoding="utf-8"))["files"]
    o.append("static const struct { const char *path, *file; uint32_t len; const char *hdr; int ok; const char *name; "
             "uint32_t datasize; uint16_t blocks; } KB[] = {\n")
    folders = {}
    for i, r in enumerate(rows):
        h = bytes.fromhex(r["hdr"])
        fake = h + bytes(max(0, r["len"] - len(h)))
        folder, fn = r["path"].rsplit("/", 1)
        try:
            d = bupfile.decode(fake)[0]
            ok, name, size, blocks = 1, d.name, d.datasize, d.blocks
            folders.setdefault(folder, {})[fn] = (i, fake)
        except bupfile.BupError:
            ok, name, size, blocks = 0, b"", 0, 0
        o.append(f"  {{ {cb(r['path'].encode())}, {cb(fn.encode())}, {r['len']}u, {cb(h)}, "
                 f"{ok}, {cb(name)}, {size}u, {blocks}u }},\n")
    o.append("};\n" f"#define KB_N {len(rows)}u\n")
    groups = []
    for folder, files in sorted(folders.items()):
        win = bupfile.index_folder({fn: b for fn, (i, b) in files.items()})
        for name, fn in sorted(win.items()):
            same = [i for f2, (i, b) in sorted(files.items()) if bupfile.decode(b)[0].name == name]
            if len(same) > 1:
                groups.append((same, files[fn][0]))
    width = max([4] + [len(same) for same, _ in groups])
    o.append(f"#define KB_DUP_W {width}u\n")
    o.append("static const struct { int idx[KB_DUP_W]; unsigned n; int winner; } KB_DUP[] = {\n")
    for same, w in groups:
        o.append("  { { " + ", ".join(str(x) for x in same + [-1] * (width - len(same)))
                 + f" }}, {len(same)}u, {w} }},\n")
    o.append("};\n" f"#define KB_NDUP {len(groups)}u\n")


def strlist(name, items):
    if not items:
        return f"static const char *const {name}[1] = {{ NULL }};\n"
    return f"static const char *const {name}[] = {{ " + ", ".join(c(x) for x in items) + " };\n"


def main(out_path):
    o = ["/* generated by menu/host-tests/gen_cases.py -- do not edit */\n"]
    mc = json.loads((FIX / "match_cases.json").read_text(encoding="utf-8"))
    o.append(strlist("MC_KEYS", mc["keys"]))
    o.append(f"#define MC_NKEYS {len(mc['keys'])}u\n")
    al = sorted(mc["aliases"].items())
    o.append("static const char *const MC_ALIASES[][2] = { " + ", ".join(f"{{ {c(a)}, {c(k)} }}" for a, k in al) + " };\n")
    o.append(f"#define MC_NALIASES {len(al)}u\n")
    o.append("static const struct { const char *product, *area, *key, *how; } MC_CASES[] = {\n")
    for x in mc["cases"]:
        o.append(f"  {{ {c(x['product'])}, {c(x['area'])}, {c(x['expect_key'])}, {c(x['expect_how'])} }},\n")
    o.append("};\n")
    o.append(f"#define MC_NCASES {len(mc['cases'])}u\n")
    rh = json.loads((FIX / "real_headers.json").read_text(encoding="utf-8"))["entries"]
    o.append("static const struct { const char *file, *hex, *product, *device, *area, *title, *date; } RH[] = {\n")
    for e in rh:
        o.append(f"  {{ {c(e['file'])}, {c(e['raw_hex'])}, {c(e['product'])}, {c(e['device'])}, {c(e['area'])}, "
                 f"{c(None if chr(0xFFFD) in e['title'] else e['title'])}, {c(e['date'])} }},\n")
    o.append("};\n")
    o.append(f"#define RH_N {len(rh)}u\n")
    fp = json.loads((FIX / "fingerprint_cases.json").read_text(encoding="utf-8"))["cases"]
    for i, x in enumerate(fp):
        o.append(strlist(f"FP{i}", x["names"]))
    o.append("static const struct { const char *const *names; unsigned n; unsigned expect; } FPC[] = {\n")
    for i, x in enumerate(fp):
        o.append(f"  {{ FP{i}, {len(x['names'])}u, {x['expect']}u }},\n")
    o.append("};\n")
    o.append(f"#define FPC_N {len(fp)}u\n")
    st = json.loads((FIX / "scan_tree.json").read_text(encoding="utf-8"))
    for i, (path, node) in enumerate(st["tree"].items()):
        o.append(strlist(f"STD{i}", node["dirs"]))
        o.append(strlist(f"STF{i}", node["files"]))
    o.append("static const struct { const char *path; const char *const *dirs; unsigned nd; "
             "const char *const *files; unsigned nf; } ST_DIRS[] = {\n")
    for i, (path, node) in enumerate(st["tree"].items()):
        o.append(f"  {{ {c(path)}, STD{i}, {len(node['dirs'])}u, STF{i}, {len(node['files'])}u }},\n")
    o.append("};\n")
    o.append(f"#define ST_NDIRS {len(st['tree'])}u\n")
    o.append("static const struct { const char *path, *product, *area, *device, *title; } ST_SYS[] = {\n")
    for p, f in st["sysids"].items():
        o.append(f"  {{ {c(p)}, {c(f['product'])}, {c(f['area'])}, {c(f['device'])}, {c(f['title'])} }},\n")
    o.append("};\n")
    o.append(f"#define ST_NSYS {len(st['sysids'])}u\n#define ST_BUILD_DATE {st['build_date']}u\n")
    for i, (p, names) in enumerate(st["cues"].items()):          # 2026-11-23: each cue's FILE names
        o.append(strlist(f"STC{i}", names))
    o.append("static const struct { const char *path; const char *const *names; unsigned n; } ST_CUES[] = {\n")
    for i, (p, names) in enumerate(st["cues"].items()):
        o.append(f"  {{ {c(p)}, STC{i}, {len(names)}u }},\n")
    o.append("};\n")
    o.append(f"#define ST_NCUES {len(st['cues'])}u\n")
    body = bytes(range(100))
    hdr = make_header(body)
    o.append("static const uint8_t LH_BODY[] = { " + ", ".join(str(b) for b in body) + " };\n")
    o.append(f"#define LH_BODY_LEN {len(body)}u\n")
    o.append("static const uint8_t LH_HDR[4096] = { " + ", ".join(str(b) for b in hdr) + " };\n")
    bup_cases(o)
    Path(out_path).write_text("".join(o), encoding="ascii")


if __name__ == "__main__":
    main(sys.argv[1])
